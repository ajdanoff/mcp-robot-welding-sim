from __future__ import annotations


from dataclasses import dataclass, field

import numpy as np


SUPPORTED_MOVE_TYPES = {"MOVJ", "MOVL"}
SUPPORTED_ARC_STATES = {"ARC_ON", "ARC_OFF", None}
SUPPORTED_PROGRAM_DIALECTS = {"melfa", "gcode"}


@dataclass(frozen=True)
class TrajectoryWaypoint:
    label: str
    move_type: str
    xyz_mm: np.ndarray
    joints_deg: np.ndarray
    arc_state: str | None = None
    speed_mm_s: float = 50.0

    def __post_init__(self) -> None:
        if self.move_type not in SUPPORTED_MOVE_TYPES:
            supported_move_types = ", ".join(
                sorted(SUPPORTED_MOVE_TYPES)
            )

            raise ValueError(
                f"Unsupported move type: '{self.move_type}'. "
                f"Supported types: {supported_move_types}."
            )

        if self.arc_state not in SUPPORTED_ARC_STATES:
            supported_states = ", ".join(
                str(state)
                for state in SUPPORTED_ARC_STATES
            )

            raise ValueError(
                f"Unsupported arc state: '{self.arc_state}'. "
                f"Supported states: {supported_states}."
            )
        
        if self.speed_mm_s <= 0:
            raise ValueError("speed_mm_s must be positive.")

        xyz = np.asarray(self.xyz_mm, dtype=np.float64)

        if xyz.shape != (3,):
            raise ValueError("xyz_mm must contain exactly three coordinates.")

        joints = np.asarray(self.joints_deg, dtype=np.float64)

        if joints.shape != (6,):
            raise ValueError(
                "joints_deg must contain exactly six joint values."
            )

        object.__setattr__(self, "xyz_mm", xyz)
        object.__setattr__(self, "joints_deg", joints)


def _validate_program_name(program_name: str) -> str:
    program_name = program_name.strip()

    if not program_name:
        raise ValueError("Program name must not be empty.")

    return program_name


def _compile_gcode(
    waypoints: list[TrajectoryWaypoint],
    program_name: str,
) -> str:
    lines: list[str] = [
        f"; PROGRAM: {program_name}",
        "; GENERATED BY MCP-ROBOT-WELDING-SIM",
        "G21 ; Millimeters",
        "G90 ; Absolute positioning",
    ]

    for waypoint in waypoints:
        x, y, z = waypoint.xyz_mm

        feed_mm_min = int(waypoint.speed_mm_s * 60.0)

        if waypoint.move_type == "MOVJ":
            motion_command = "G00"
        else:
            motion_command = "G01"

        lines.append(
            f"{motion_command} "
            f"X{x:.3f} "
            f"Y{y:.3f} "
            f"Z{z:.3f} "
            f"F{feed_mm_min} "
            f"; {waypoint.label}"
        )

        if waypoint.arc_state == "ARC_ON":
            lines.append("M03 S100 ; TORCH ARC ON")
        elif waypoint.arc_state == "ARC_OFF":
            lines.append("M05 ; TORCH ARC OFF")

    lines.append("M30 ; End of program")

    return "\n".join(lines)


def _compile_melfa(
    waypoints: list[TrajectoryWaypoint],
    program_name: str,
) -> str:
    lines: list[str] = [
        f"' PROGRAM: {program_name}",
        "' GENERATED BY MCP-ROBOT-WELDING-SIM",
        "SERVO ON",
        "OVRD 50",
    ]

    for waypoint_index, waypoint in enumerate(
        waypoints,
        start=1,
    ):
        x, y, z = waypoint.xyz_mm

        lines.append(
            f"P{waypoint_index} = "
            f"({x:.3f}, {y:.3f}, {z:.3f}, "
            f"180.000, 0.000, 180.000)(6, 0)"
        )

    lines.append("")

    for waypoint_index, waypoint in enumerate(
        waypoints,
        start=1,
    ):
        lines.append(
            f"SPD {waypoint.speed_mm_s:.3f}"
        )

        lines.append(
            f"{waypoint.move_type} "
            f"P{waypoint_index} "
            f"' {waypoint.label}"
        )

        if waypoint.arc_state == "ARC_ON":
            lines.append(
                "HOPEN 1 ' ARC_START (WELDING POWER ON)"
            )
            lines.append("DLY 0.300")
        elif waypoint.arc_state == "ARC_OFF":
            lines.append(
                "HCLOSE 1 ' ARC_END (WELDING POWER OFF)"
            )
            lines.append("DLY 0.200")

    lines.append("SERVO OFF")
    lines.append("END")

    return "\n".join(lines)


def compile_program(
    waypoints: list[TrajectoryWaypoint],
    dialect: str = "melfa",
    program_name: str = "WELD_JOB_01",
) -> str:
    """
    Compiles validated waypoints into target industrial robot controller code.

    Supported dialects:
    - 'melfa': MELFA-BASIC-style program.
    - 'gcode': G-code-style program.
    """
    if not waypoints:
        raise ValueError("At least one trajectory waypoint is required.")

    normalized_dialect = dialect.strip().lower()

    if normalized_dialect not in SUPPORTED_PROGRAM_DIALECTS:
        raise ValueError(
            f"Unsupported dialect: '{dialect}'. "
            f"Supported dialects: "
            f"{sorted(SUPPORTED_PROGRAM_DIALECTS)}."
        )

    validated_program_name = _validate_program_name(program_name)

    if normalized_dialect == "gcode":
        return _compile_gcode(
            waypoints=waypoints,
            program_name=validated_program_name,
        )

    return _compile_melfa(
        waypoints=waypoints,
        program_name=validated_program_name,
    )